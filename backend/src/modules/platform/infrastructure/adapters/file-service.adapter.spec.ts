import type { FileDto } from '@contrack/contract';
import { UploadFileUseCase } from '../../application/use-cases/upload-file.use-case';
import { PlatformTestKit, errorOf, outcome, valueOf } from '../../testing/platform-test-kit';
import { RepositoryFileService } from './file-service.adapter';

describe('RepositoryFileService', () => {
    let kit: PlatformTestKit;
    let upload: UploadFileUseCase;
    let service: RepositoryFileService;

    beforeEach(() => {
        kit = new PlatformTestKit();
        upload = new UploadFileUseCase(kit.files, kit.storage, kit.links, kit.settings, kit.clock, kit.ids, kit.roles);
        service = new RepositoryFileService(kit.files, kit.links, upload);
    });

    async function add(name: string, by = kit.newUserId()): Promise<FileDto> {
        return valueOf(await upload.execute({ actorId: by, purpose: 'bid_photo', name, contentType: 'image/jpeg', bytes: new Uint8Array([1]) }));
    }

    it('describe: DTOs in the order given, unknown and malformed ids skipped, fresh links', async () => {
        const a = await add('a.jpg');
        const b = await add('b.jpg');
        const out = await service.describe([b.id, 'not-a-uuid', '00000000-0000-4000-8000-00000000ffff', a.id.toUpperCase()]);
        expect(out.map(f => f.name)).toEqual(['b.jpg', 'a.jpg']);
        expect(out[0]?.url).toMatch(/^\/api\/files\//);
        expect(await service.describe([])).toEqual([]);
    });

    it('assertUploadedBy: ok when every file is the user\'s (and for no files)', async () => {
        const me = kit.newUserId();
        const a = await add('a.jpg', me);
        const b = await add('b.jpg', me);
        expect(outcome(await service.assertUploadedBy([a.id, b.id], me))).toBe('ok');
        expect(outcome(await service.assertUploadedBy([], me))).toBe('ok');
    });

    it('assertUploadedBy: someone else\'s, unknown or malformed file is unprocessable (with the id)', async () => {
        const me = kit.newUserId();
        const mine = await add('a.jpg', me);
        const theirs = await add('b.jpg');
        expect(errorOf(await service.assertUploadedBy([mine.id, theirs.id], me))).toMatchObject({ code: 'unprocessable', details: { fileId: theirs.id } });
        expect(outcome(await service.assertUploadedBy(['00000000-0000-4000-8000-00000000ffff'], me))).toBe('unprocessable');
        expect(outcome(await service.assertUploadedBy(['nope'], me))).toBe('unprocessable');
    });

    it('store: keeps server-generated bytes and answers the DTO', async () => {
        const by = kit.newUserId();
        const dto = await service.store({ name: 'contract.pdf', contentType: 'application/pdf', bytes: new Uint8Array([1, 2]), uploadedBy: by, purpose: 'contract_pdf' });
        expect(dto).toMatchObject({ name: 'contract.pdf', size: 2, contentType: 'application/pdf' });
        expect(outcome(await service.assertUploadedBy([dto.id], by))).toBe('ok');
    });

    it('store: a refused type is a programming error (throws)', async () => {
        await expect(service.store({ name: 'x.txt', contentType: 'text/plain', bytes: new Uint8Array([1]), uploadedBy: kit.newUserId(), purpose: 'contract_pdf' }))
            .rejects.toThrow(/not allowed/);
    });
});
