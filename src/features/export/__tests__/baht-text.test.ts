import { describe, expect, it } from 'vitest';
import { bahtText } from '../baht-text';

describe('bahtText', () => {
    it.each([
        [0, 'ศูนย์บาทถ้วน'],
        [1, 'หนึ่งบาทถ้วน'],
        [10, 'สิบบาทถ้วน'],
        [11, 'สิบเอ็ดบาทถ้วน'],
        [21, 'ยี่สิบเอ็ดบาทถ้วน'],
        [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
        [7500, 'เจ็ดพันห้าร้อยบาทถ้วน'],
        [1_000_000, 'หนึ่งล้านบาทถ้วน'],
        [1_000_001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
        [21_000_000, 'ยี่สิบเอ็ดล้านบาทถ้วน'],
        [1_850_317.34, 'หนึ่งล้านแปดแสนห้าหมื่นสามร้อยสิบเจ็ดบาทสามสิบสี่สตางค์'],
        [0.5, 'ห้าสิบสตางค์'],
        [-25.25, 'ลบยี่สิบห้าบาทยี่สิบห้าสตางค์'],
        [1.999, 'สองบาทถ้วน'],
    ])('%d → %s', (n, words) => {
        expect(bahtText(n)).toBe(words);
    });

    it('returns empty text for non-finite numbers', () => {
        expect(bahtText(Number.NaN)).toBe('');
    });
});
